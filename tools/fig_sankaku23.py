# 栄光 10月ターム 算数「三角形の面積」確認問題の図（images/tr23_*.svg）
import math, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from figlib_parallelogram import make
def foot(P, C, d):
    t = (P[0]-C[0])*d[0] + (P[1]-C[1])*d[1]; return (C[0]+t*d[0], C[1]+t*d[1])
# 1 平行な2本の線の間の ア・イ・ウ
ta = [(2,0),(12,0),(7,9)]; ti = [(14,0),(22,0),(24,9)]; tu = [(25,0),(37,0),(27,9)]
make('tr23_1.svg', ta, polys=[ti, tu], lines=[((-4,0),(40,0)),((-4,9),(40,9))],
     dashed=[((-2,0),(-2,9))], rights=[((-2,0),(1,0),(0,1)),((-2,9),(1,0),(0,-1))], target=500,
     dims=[((2,0),(12,0),'10cm',-1),((14,0),(22,0),'8cm',-1),((25,0),(37,0),'12cm',-1),((-2,0),(-2,9),'9cm',1)],
     marks=[('ア',(7,3)),('イ',(20,3)),('ウ',(29.7,3))])
# 2-(1) 底辺13 高さ8
make('tr23_2_1.svg', [(0,0),(13,0),(11,8)], dashed=[((11,8),(11,0))], rights=[((11,0),(-1,0),(0,1))],
     dims=[((0,0),(13,0),'13cm',-1),((11,0),(11,8),'8cm',1)])
# 2-(2) 底辺12 高さ11（外）
make('tr23_2_2.svg', [(0,0),(12,0),(16,11)], dashed=[((16,11),(16,0))], dotted=[((12,0),(16,0))], rights=[((16,0),(-1,0),(0,1))],
     dims=[((0,0),(12,0),'12cm',-1),((16,0),(16,11),'11cm',-1)])
# 2-(3) 辺15 その辺への高さ14 底辺16
sn = 14/16; d = (math.sqrt(1-sn*sn), sn); A = (15*d[0], 15*d[1]); C = (16,0); F = foot(C,(0,0),d)
make('tr23_2_3.svg', [(0,0),C,A], dashed=[(C,F)], rights=[(F,(-d[0],-d[1]),(C[0]-F[0],C[1]-F[1]))],
     dims=[((0,0),C,'16cm',-1),((0,0),A,'15cm',1),(F,C,'14cm',1)])
# 4-(1) 辺12 高さ8 底辺□ 面積56
ax = math.sqrt(144-64)
make('tr23_4_1.svg', [(0,0),(14,0),(ax,8)], dashed=[((ax,8),(ax,0))], rights=[((ax,0),(1,0),(0,1))],
     dims=[((0,0),(14,0),'□cm',-1),((0,0),(ax,8),'12cm',1),((ax,0),(ax,8),'8cm',1)], area='56cm²')
# 4-(2) 底辺29 辺21 その辺への高さ□ 面積273
sn = 26/29; d = (-math.sqrt(1-sn*sn), sn); C = (29,0); A = (C[0]+21*d[0], 21*d[1]); F = foot((0,0),C,d)
make('tr23_4_2.svg', [(0,0),C,A], dashed=[((0,0),F)], rights=[(F,(d[0],d[1]),(-F[0],-F[1]))],
     dims=[((0,0),C,'29cm',-1),(C,A,'21cm',-1),((0,0),F,'□cm',-1)], area='273cm²')
# 4-(3) 底辺□ 辺26 高さ24（外） 面積234
make('tr23_4_3.svg', [(0,0),(19.5,0),(29.5,24)], dashed=[((29.5,24),(29.5,0))], dotted=[((19.5,0),(29.5,0))], rights=[((29.5,0),(-1,0),(0,1))],
     dims=[((0,0),(19.5,0),'□cm',-1),((19.5,0),(29.5,24),'26cm',1),((29.5,0),(29.5,24),'24cm',-1)], area='234cm²')
# 4-(4) 辺18・24 底辺30 高さ□ 面積216
A = (10.8,14.4)
make('tr23_4_4.svg', [(0,0),(30,0),A], dashed=[(A,(10.8,0))], rights=[((10.8,0),(1,0),(0,1))],
     dims=[((0,0),(30,0),'30cm',-1),((0,0),A,'18cm',1),((30,0),A,'24cm',-1),((10.8,0),A,'□cm',-1)], area='216cm²')
print('ok')
