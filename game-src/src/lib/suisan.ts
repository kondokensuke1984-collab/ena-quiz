export const STAGE_BY_ID: Record<string, Stage> = Object.fromEntries(STAGES.map((s) => [s.id, s]));

export const GOOD_MONEY = 12;   // 1回めで せいかい
export const RETRY_MONEY = 4;   // やりなおして せいかい

/** そのステージを あそべるか（さきの ステージを クリアしたか） */
export const unlocked = (st: Stage, cleared: string[]): boolean => st.needs.every((id) => cleared.includes(id));
export const lockHint = (st: Stage, cleared: string[]): string => {
  const need = st.needs.filter((id) => !cleared.includes(id)).map((id) => STAGE_BY_ID[id].name);
  return need.length ? `さきに「${need.join('・')}」を クリア` : '';
};

export function clearLine(st: Stage, money: number): string {
  return `${st.name}を クリア！ 水あげは ${money}万円 に なったよ`;
}

/** 日付で ひらく（2026-10-31から）。?suisan=1 か ?today=YYYY-M-D で 確認できる */
export const SUISAN_OPEN_FROM = { y: 2026, m: 10, d: 31 };
/** さきに あそべる 主人公（ためしあそび）。ほかの子は 公開日から */
const EARLY_PLAYERS = ['kensuke', 'mitsuki'];
export function suisanOpen(player: string | null = null, now = new Date(), search = typeof location !== 'undefined' ? location.search : ''): boolean {
  if (player && EARLY_PLAYERS.includes(player)) return true;
  try {
    const q = new URLSearchParams(search);
    if (q.get('suisan') === '1') return true;
    const t = q.get('today');
    if (t) {
      const m = /^(\d{4})-(\d{1,2})-(\d{1,2})$/.exec(t);
      if (m) now = new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
    }
  } catch { /* そのまま */ }
  const open = new Date(SUISAN_OPEN_FROM.y, SUISAN_OPEN_FROM.m - 1, SUISAN_OPEN_FROM.d);
  return now.getTime() >= open.getTime();
}
